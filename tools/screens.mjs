// Headless walk-through of the demo + screenshots (no window is opened).
//   BASE=http://localhost:52795 OUT=_screens node tools/screens.mjs
import { chromium } from "playwright";
const BASE = process.env.BASE || "http://localhost:52795";
const OUT = process.env.OUT || "_screens";
const RN = process.env.RN || "D-1226-2015";
const api = (p, m = "GET", b) => fetch(BASE + "/recallreach/api" + p, { method: m, headers: { "Content-Type": "application/json" }, body: b ? JSON.stringify(b) : undefined }).then(r => r.json().then(j => ({ s: r.status, j })));
const sleep = ms => new Promise(r => setTimeout(r, ms));
const log = (...a) => console.log(...a);

const b = await chromium.launch({ headless: true, executablePath: process.env.CHROME || undefined });
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
const page = await ctx.newPage();
page.on("pageerror", e => log("PAGE ERROR", e.message));
const shot = async (n) => { await page.screenshot({ path: `${OUT}/${n}.png` }); log("shot", n); };

await api("/demo/reset", "POST");
// video scenario: weeks earlier, the pharmacist scanned the box when filling patient 10002428 (fill 1115)
await page.goto(BASE + "/recallreach/index.html#/scan");
await page.click("#sample"); await sleep(600); await page.click("#parse");
await page.waitForSelector('.rec[data-id="1115"]', { timeout: 15000 });
await page.click('.rec[data-id="1115"]'); await sleep(800);
await shot("00_scan_lot_at_dispensing");
await page.goto(BASE + "/recallreach/index.html#/");
await page.waitForSelector(".rcard");
await shot("01_inbox");
await page.click("#sim");
await sleep(700); await shot("02_new_recall_arriving");
await page.waitForFunction(rn => [...document.querySelectorAll(".rcard")].some(c => c.href.includes(rn) && c.querySelector(".count .n")), RN, { timeout: 60000 });
await sleep(400); await shot("03_new_recall_read");
await page.goto(BASE + "/recallreach/index.html#/recall/" + RN);
await page.waitForSelector(".field");
await page.hover('.field[data-f]:nth-child(7)').catch(() => {});
await sleep(300); await shot("04_recall_detail");
await page.click("#find");
await sleep(900); await shot("05_find_patients_spinning");
await sleep(2600); await shot("06_patient_list_top");
await page.click("#plist .prow .exp"); await sleep(300);
await shot("07_why_this_probability");
await page.click("#hb").catch(() => {}); await sleep(300);
await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight)); await sleep(300);
await shot("08_hidden_low_likelihood");
await page.click("#ask");
await page.waitForSelector("#ok"); await sleep(1200);
await shot("09_approval_10min_single_use");
const token = page.url().split("/approve/")[1];
await page.click("#ok"); await sleep(3500);
await shot("10_approved");
const again = await api(`/approvals/${token}/approve`, "POST");
log("re-use approval ->", again.s, again.j.error);
await page.goto(BASE + "/recallreach/index.html#/recall/" + RN + "/patients");
await sleep(1500); await shot("11_after_approval_holds");
await page.goto(BASE + "/recallreach/index.html#/accuracy");
await page.waitForSelector(".big3", { timeout: 60000 }); await sleep(300);
await shot("13_accuracy");
await page.goto(BASE + "/recallreach/index.html#/audit");
await page.waitForSelector(".evt"); await sleep(300);
await shot("14_audit_trail");
await page.setViewportSize({ width: 390, height: 844 });
await page.goto(BASE + "/recallreach/index.html#/recall/" + RN + "/patients"); await sleep(1500);
await shot("15_phone_width");
await b.close();
